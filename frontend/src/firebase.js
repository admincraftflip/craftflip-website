import { initializeApp } from 'firebase/app'
import { getAuth } from 'firebase/auth'

const firebaseConfig = {
  apiKey: import.meta.env.VITE_FIREBASE_API_KEY,
  authDomain: import.meta.env.VITE_FIREBASE_AUTH_DOMAIN,
  projectId: import.meta.env.VITE_FIREBASE_PROJECT_ID,
  storageBucket: import.meta.env.VITE_FIREBASE_STORAGE_BUCKET,
  messagingSenderId: import.meta.env.VITE_FIREBASE_MESSAGING_SENDER_ID,
  appId: import.meta.env.VITE_FIREBASE_APP_ID,
}

const missingKeys = Object.entries(firebaseConfig)
  .filter(([, value]) => !value)
  .map(([key]) => key)

if (missingKeys.length > 0) {
  console.error(`Firebase config is incomplete. Missing values in frontend/.env for: ${missingKeys.join(', ')}`)
}

export const firebaseApp = initializeApp(firebaseConfig)

// getAuth uses Firebase's default browser persistence (IndexedDB, falling back to localStorage),
// so sessions survive reloads without the app ever storing tokens itself.
export const auth = getAuth(firebaseApp)
